const clamp01 = (x) => Math.min(1, Math.max(0, x));

/** The colour of `t` (clamped to [0, 1]) in colormap `name` (unknown names: viridis). */
export function colormap(name, t) {
  t = clamp01(t);
  if (name === "greys") return [t, t, t];
  const c = FITS[name] ?? FITS.viridis;
  const rgb = [0, 0, 0];
  // Horner's scheme, highest degree first.
  for (let i = c.length - 1; i >= 0; i--) for (let k = 0; k < 3; k++) rgb[k] = rgb[k] * t + c[i][k];
  return rgb.map(clamp01);
}
